def apply_translations(html, language, page_rel):
    """Apply shared + page-specific translations to html via longest-first replace."""
    entries = []
    entries.extend(SHARED)
    for pg, en, ms, zh_ in PAGE:
        if pg == page_rel:
            entries.append((en, ms, zh_))
    # de-dup, longest english first (avoid short "Home" clobbering longer matches before them)
    by_en = {}
    for en, ms, zh_ in entries:
        by_en[en] = (ms, zh_)
    ordered = sorted(by_en.items(), key=lambda kv: -len(kv[0]))
    for en, (ms, zh_) in ordered:
        val = ms if language == "ms" else zh_
        if en in html:
            html = html.replace(en, val)
    return html


def retarget_refs(html, page_dir, lang):
    """Rewrite local href/src/url() refs.

    Page links (.html) are retargeted into the language subtree; shared assets
    (.css/.js/images/fonts) stay at the site root. Both are expressed as paths
    relative to the translated page's own directory.
    """
    def rewrite(ref):
        if ref.startswith(("#", "http:", "https:", "mailto:", "tel:", "data:", "//")):
            return ref
        # strip fragment/query for path resolution
        path_part = ref.split("#", 1)[0]
        frag = ref[len(path_part):]
        target = os.path.normpath(os.path.join(page_dir, path_part))
        site_rel = os.path.relpath(target, ROOT)
        out_dir = os.path.join(lang, page_dir)
        if site_rel.lower().endswith(".html") and not site_rel.startswith("insights/"):
            # page link into the language subtree (blog articles stay English-only)
            target_path = os.path.join(lang, site_rel)
            href = os.path.relpath(target_path, out_dir)
        else:
            # asset or English-only blog article -> site root (no language prefix)
            href = os.path.relpath(site_rel, out_dir)
        return href + frag

    # rewrite href and src attributes
    def repl_attr(m):
        attr, val = m.group(1), m.group(2)
        return f'{attr}="{rewrite(val)}"'

    html = re.sub(r'(href|src)="([^"]+)"', repl_attr, html)
    # css url()
    html = re.sub(r'url\((["\']?)([^"\')\s]+)\1\)', lambda m: f'url({m.group(1)}{rewrite(m.group(2))}{m.group(1)})', html)
    return html


def head_meta(html, page_rel, lang):
    """Rewrite lang, canonical, hreflang, title/meta (page-specific handled earlier)."""
    # html lang
    new_lang = "ms-MY" if lang == "ms" else "zh-CN"
    html = re.sub(r'<html[^>]*lang="[^"]*"', '<html lang="%s"' % new_lang, html, count=1)
    # mapping of site-relative original page path -> language-prefixed page path
    def mapped(path):
        # path like "index.html" or "services/build.html"
        return os.path.join(lang, path).replace("\\", "/")

    current = mapped(page_rel)
    alt_map = {
        "en": page_rel,
        "ms": mapped(page_rel) if lang != "ms" else page_rel,
        "zh": mapped(page_rel) if lang != "zh" else page_rel,
    }
    # Wait: for the language being generated, its own canonical URL is the lang-prefixed one.
    # Build alternates: en, ms, zh each pointing to their own URL; current lang links to all three.
    en_ref = "" if page_rel == "index.html" else page_rel
    alt_links = ""
    for alt_lang, alt_rel in [("en-MY", en_ref), ("ms-MY", "ms/%s" % page_rel), ("zh-CN", "zh/%s" % page_rel)]:
        alt_links += f'<link rel="alternate" hreflang="{alt_lang}" href="{BASE}{alt_rel}">\n    '
    alt_links += f'<link rel="alternate" hreflang="x-default" href="{BASE}{en_ref}">\n    '
    # canonical for current language
    canon = f'<link rel="canonical" href="{BASE}{current}">'

    # Find existing canonical and hreflang block. English pages have:
    #   <link rel="alternate" hreflang="en-MY" href="...">
    #   <link rel="alternate" hreflang="x-default" href="...">
    # Replace any existing single canonical, and existing hreflang alternates with the new triple.
    # canonical
    html = re.sub(
        r'<link rel="canonical" href="[^"]*"[^>]*>',
        f'<link rel="canonical" href="{BASE}{current}">',
        html,
        count=1,
    )
    # og:url (exact URL used by twitter/og may omit file for index; rewrite to lang URL)
    html = re.sub(
        r'(property="og:url" content=")[^"]*(")',
        lambda m: m.group(1) + BASE + current + m.group(2),
        html,
        count=1,
    )
    # drop any existing hreflang lines (tolerate ` />`)
    html = re.sub(
        r'\n?\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*"\s*/?>',
        "",
        html,
    )
    # insert alternate links right before the canonical link so head stays clean
    html = html.replace(f'<link rel="canonical" href="{BASE}{current}">', alt_links + '    \n' + f'<link rel="canonical" href="{BASE}{current}">')
    return html


def inject_switcher(html, base_dir, lang, page_rel):
    """Add a language switcher in the footer, directly below the office-hours
    widget (before the social "Follow Us" widget heading).

    base_dir is the directory (relative to site root) the page sits in for
    the language being produced: language/ + page_dir for ms/zh, or just
    page_dir for English.
    """
    def lang_href(prefix):
        if prefix:
            other_file = os.path.join(prefix, page_rel)
        else:
            other_file = page_rel
        return os.path.relpath(other_file, base_dir).replace("\\", "/")

    targets = {
        "en": ("EN", "English", "", ""),
        "ms": ("BM", "Bahasa Melayu", "", "ms"),
        "zh": ("ZH", "\u4e2d\u6587", "", "zh"),
    }
    parts = []
    for code, (short, long_name, _hl, prefix) in targets.items():
        active = " active" if code == lang else ""
        href = lang_href(prefix)
        parts.append(
            f'<a href="{href}" class="lang-switch-link{active}"'
            f' aria-label="{code}" title="{long_name}"'
            f'>{short}<span class="visually-hidden">{long_name}</span></a>'
        )
    switcher_html = '<div class="lang-switcher" aria-label="Language switcher">' + "".join(parts) + "</div>"

    # Insert the switcher as a sibling just below the office-hours widget, i.e.
    # immediately before the whole Follow Us footer-widget heading element.
    if '<div class="lang-switcher"' in html:
        return html  # idempotent
    m = re.search(r'\s*<h2 class="footer-widget__title h6 mb-30 mt-4">.*?</h2>', html, flags=re.S)
    if m:
        html = html[:m.start()] + "\n                            " + switcher_html + m.group(0) + html[m.end():]
    return html


def english_alternate_links(page_rel):
    """Three-alternate hreflang block (en/ms/zh + x-default)."""
    en_ref = "" if page_rel == "index.html" else page_rel
    rows = [
        ("en-MY", en_ref),
        ("ms-MY", "ms/" + page_rel),
        ("zh-CN", "zh/" + page_rel),
    ]
    out = "".join(
        f'    <link rel="alternate" hreflang="{hl}" href="{BASE}{href}">\n'
        for hl, href in rows
    )
    out += f'    <link rel="alternate" hreflang="x-default" href="{BASE}{en_ref}">\n'
    return out


def patch_english_sources():
    """Update English pages: full hreflang triple + footer switcher (EN active)."""
    pages = [
        "index.html", "about.html", "services.html", "solutions.html",
        "contact.html", "careers.html", "insights.html",
        "services/build.html", "services/connect.html", "services/support.html",
        "solutions/industries.html", "solutions/integrations.html", "solutions/platforms.html",
    ]
    for page_rel in pages:
        path = os.path.join(ROOT, page_rel)
        html = open(path, encoding="utf-8").read()
        changed = False

        # Replace the existing en-MY + x-default hreflang lines with the full triple
        pat = re.compile(
            r'<link rel="alternate" hreflang="[^"]*" href="[^"]*"\s*/?>(?:\s*<link rel="alternate" hreflang="[^"]*" href="[^"]*"\s*/?>)+'
        )
        if pat.search(html):
            html = pat.sub(lambda m: english_alternate_links(page_rel), html, count=1)
            changed = True
        else:
            # No existing hreflang alternates (sub-pages): insert before canonical
            canon = re.search(r'<link rel="canonical" href="[^"]*"\s*/?>', html)
            if canon:
                html = html.replace(canon.group(0), english_alternate_links(page_rel) + canon.group(0), 1)
                changed = True

        # Inject footer switcher (English active)
        html = inject_switcher(html, os.path.dirname(page_rel), "en", page_rel)
        changed = True

        if changed:
            open(path, "w", encoding="utf-8").write(html)
            print("patched", page_rel)

def main():
    pages = [
        "index.html", "about.html", "services.html", "solutions.html",
        "contact.html", "careers.html", "insights.html",
        "services/build.html", "services/connect.html", "services/support.html",
        "solutions/industries.html", "solutions/integrations.html", "solutions/platforms.html",
    ]
    for lang in ("ms", "zh"):
        for page_rel in pages:
            src = os.path.join(ROOT, page_rel)
            out = os.path.join(ROOT, lang, page_rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            html = open(src, encoding="utf-8").read()
            page_dir = os.path.dirname(page_rel)
            html = apply_translations(html, lang, page_rel)
            html = retarget_refs(html, page_dir, lang)
            html = head_meta(html, page_rel, lang)
            html = inject_switcher(html, os.path.join(lang, page_dir), lang, page_rel)
            # final: ensure html lang attribute consistent
            open(out, "w", encoding="utf-8").write(html)
            print(f"wrote {os.path.relpath(out, ROOT)}")
    patch_english_sources()
    print("done")


